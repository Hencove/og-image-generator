// Helper function to determine gradient based on category
function getGradientForCategory(category?: string): string {
  if (!category) {
    return 'linear-gradient(30deg, rgba(102, 11, 182, 0.5), rgba(252, 194, 56, 0.5))';
  }

  const normalizedCategory = category.toLowerCase().trim();

  switch (normalizedCategory) {
    case 'news':
      return 'linear-gradient(30deg, rgba(102, 11, 182, 0.5), rgba(252, 194, 56, 0.5))';
    case 'case study':
      return 'linear-gradient(90deg, rgba(1, 0, 116, 0.5), rgba(0, 0, 0, 0.5))';
    case 'blog':
      return 'linear-gradient(120deg, rgba(138, 223, 27, 0.5), rgba(1, 0, 116, 0.5))';
    default:
      return 'linear-gradient(30deg, rgba(102, 11, 182, 0.5), rgba(252, 194, 56, 0.5))';
  }
}

